import { test, expect } from '@playwright/test';
import { mkdir, readFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import type { Garment } from '../src/lib/types';

const artifacts = process.env.ATELIER_E2E_ARTIFACT_DIR || resolve('../../.local/ui');

test('designer creates, locks, edits, undoes, saves, reloads and restores a revision', async ({page}) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  await expect(page.getByRole('heading', {name: /Your vision/})).toBeVisible();
  await page.getByRole('link', {name: /Enter your studio/}).click();
  await expect(page.getByRole('heading', {name: 'A new design starts here.'})).toBeVisible();
  await page.getByLabel('Project name', {exact: true}).last().fill('Festive commissions');
  await page.getByRole('button', {name: 'Create your first project'}).click();
  await page.getByLabel('Add a garment').fill('Burgundy blouse');
  await page.getByRole('button', {name: 'Create garment', exact: false}).click();
  await expect(page.getByRole('heading', {name: 'Burgundy blouse'})).toBeVisible();
  const sleeve = page.locator('[data-shape-id="shape:sleeve-right"]').first();
  await expect(sleeve).toBeVisible();
  const gid = new URL(page.url()).searchParams.get('garment');
  const read = async () => (await page.request.get(`/api/backend/v1/garments/${gid}`)).json() as Promise<Garment>;
  const initial = await read();
  await page.locator('.component-row').filter({hasText: 'neckline'}).click();
  await page.getByRole('button', {name: 'Lock this component'}).click();
  await expect(page.getByRole('status')).toContainText('Component locked');
  await expect(page.locator('.component-row').filter({hasText: 'neckline'})).toContainText('Locked');
  const locked = await read();
  const box = await sleeve.boundingBox();
  if (!box) throw new Error('Sleeve drawing did not render');
  await page.mouse.move(box.x + 1, box.y + 1);
  await page.mouse.down(); await page.mouse.move(box.x + 27, box.y + 17, {steps: 10}); await page.mouse.up();
  await expect(page.getByRole('button', {name: /Review changes/})).toBeEnabled();
  await page.getByRole('button', {name: /Review changes/}).click();
  await page.getByRole('button', {name: 'Commit draft'}).click();
  await expect(page.getByRole('status')).toContainText('New draft saved');
  const edited = await read();
  expect(edited.draft_revision_id).not.toBe(locked.draft_revision_id);
  expect(edited.design.components.find(c => c.id === 'neckline')).toEqual(locked.design.components.find(c => c.id === 'neckline'));
  expect(edited.approved_revision_id).toBeNull();
  const historical = await page.request.get(`/api/backend/v1/garments/${gid}/revisions/${initial.draft_revision_id}`);
  expect((await historical.json()).design).toEqual(initial.design);
  await page.reload(); await expect(sleeve).toBeVisible();
  expect((await read()).design).toEqual(edited.design);

  await page.getByRole('button', {name: 'Draw', exact: true}).click();
  const frame = await page.locator('.canvas-frame').boundingBox();
  if (!frame) throw new Error('Canvas absent');
  await page.mouse.move(frame.x + 80, frame.y + 150);
  await page.mouse.down();
  for (let i=1;i<=15;i++) await page.mouse.move(frame.x + 80 + i*3, frame.y + 150 + Math.sin(i/3)*20);
  await page.mouse.up();
  await expect(page.getByRole('button', {name: /Review changes/})).toBeEnabled();
  await page.getByRole('button', {name: 'Undo drawing edit'}).click();
  await expect(page.getByRole('button', {name: /Review changes/})).toBeDisabled();
  await page.getByRole('button', {name: 'Redo drawing edit'}).click();
  await expect(page.getByRole('button', {name: /Review changes/})).toBeEnabled();
  await page.getByRole('button', {name: /Review changes/}).click();
  await page.getByRole('button', {name: 'Commit draft'}).click();
  await expect(page.getByRole('status')).toContainText('New draft saved');
  const freehand = await read();
  expect(freehand.design.components.length).toBe(6);
  await page.reload(); await expect(page.locator('.component-row')).toHaveCount(6);
  expect((await read()).design).toEqual(freehand.design);
  await page.getByRole('button', {name: 'History', exact: true}).click();
  await page.getByRole('button', {name: /Review restoration/}).first().click();
  await page.getByRole('button', {name: 'Commit draft'}).click();
  await expect(page.getByRole('status')).toContainText('New draft saved');
  expect((await read()).design.components.length).toBe(5);
  await page.getByRole('button', {name: 'Components', exact: true}).click();
  await page.getByRole('button', {name: 'Approve aesthetics'}).click();
  await expect(page.locator('.badge')).toHaveText('Aesthetic approved');
  await page.getByRole('button', {name: 'Prepare review draft'}).click();
  await expect(page.getByRole('link', {name: 'Download review JSON'})).toBeVisible();
  const pdfLink = page.getByRole('link', {name: 'Download review PDF'});
  await expect(pdfLink).toBeVisible();
  const pdfHref = await pdfLink.getAttribute('href');
  expect(pdfHref).toBeTruthy();
  const pdfResponse = await page.request.get(pdfHref!);
  expect(pdfResponse.status()).toBe(200);
  expect(pdfResponse.headers()['content-type']).toContain('application/pdf');
  expect(pdfResponse.headers()['cache-control']).toContain('no-store');
  expect((await pdfResponse.body()).subarray(0, 5).toString()).toBe('%PDF-');
  const [download] = await Promise.all([
    page.waitForEvent('download'),
    pdfLink.click(),
  ]);
  expect(download.suggestedFilename()).toMatch(/\.pdf$/);
  const pdfPath = await download.path();
  expect(pdfPath).toBeTruthy();
  expect((await readFile(pdfPath!)).subarray(0, 5).toString()).toBe('%PDF-');
  await page.getByRole('button', {name: 'Research', exact: true}).click();
  await page.getByLabel('Source title').fill('Sleeve study');
  await page.getByLabel('Source excerpt').fill('Consider additional sleeve ease for a second fitting.');
  await page.getByLabel('Reuse rights', {exact: true}).selectOption('owned');
  await page.getByRole('button', {name: 'Save source'}).click();
  await page.getByRole('checkbox', {name: 'Sleeve study'}).check();
  await page.getByLabel('Research question').fill('Sleeve ease');
  await page.getByRole('button', {name: 'Build cited brief'}).click();
  await expect(page.getByRole('heading', {name: 'Sleeve ease'})).toBeVisible();
  await page.getByText('Add a moodboard image', {exact: true}).click();
  const swatch = await page.evaluate(() => {
    const canvas = document.createElement('canvas');
    canvas.width = 8;
    canvas.height = 8;
    const context = canvas.getContext('2d')!;
    context.fillStyle = '#587261';
    context.fillRect(0, 0, 8, 8);
    return canvas.toDataURL('image/jpeg').split(',')[1];
  });
  await page.getByLabel('JPEG image', {exact: true}).setInputFiles({name: 'swatch.jpg',
    mimeType: 'image/jpeg', buffer: Buffer.from(swatch, 'base64')});
  await page.getByLabel('Image title', {exact: true}).fill('Cotton swatch');
  await page.getByLabel('Image description', {exact: true}).fill('Green cotton reference');
  await page.getByLabel('Image reuse rights', {exact: true}).selectOption('owned');
  await page.getByRole('button', {name: 'Save moodboard image'}).click();
  await expect(page.getByRole('img', {name: 'Green cotton reference'})).toBeVisible();
  await page.getByRole('button', {name: 'Materials', exact: true}).click();
  await page.getByText('Record an offer', {exact: true}).click();
  await page.getByLabel('Material name').fill('Twill swatch');
  await page.getByLabel('Supplier evidence').fill('Synthetic swatch record for the browser test');
  await page.getByLabel('Price per metre').fill('800.00');
  await page.getByLabel('Measured stretch (%)').fill('12');
  await page.getByLabel('Availability', {exact: true}).selectOption('yes');
  await page.getByRole('button', {name: 'Save offer'}).click();
  await expect(page.getByText('Offer saved. Run a comparison to review the costs.')).toBeVisible();
  await page.getByLabel('Required length (m)').fill('3.00');
  await page.getByLabel('Trim cost').fill('200.00');
  await page.getByLabel('Other cost').fill('100.00');
  await page.getByRole('button', {name: 'Compare materials'}).click();
  await expect(page.getByText('compatible · INR 2940.00')).toBeVisible();
  await page.getByRole('button', {name: 'Review substitution'}).click();
  await page.getByRole('button', {name: 'Commit draft'}).click();
  await expect(page.locator('.badge')).toHaveText('Unapproved draft');
  await page.getByRole('button', {name: 'Components', exact: true}).click();
  await expect(page.getByText(/Earlier draft, review required/)).toBeVisible();
  await page.getByRole('button', {name: 'Reviews', exact: true}).click();
  await page.getByRole('button', {name: 'Create fixture concept'}).click();
  await expect(page.getByRole('img', {name: 'Offline garment concept'})).toBeVisible();
  await page.reload();
  await page.getByRole('button', {name: 'Reviews', exact: true}).click();
  await expect(page.getByText('awaiting review · Current revision')).toBeVisible();
  await page.getByRole('button', {name: 'Cancel review request'}).click();
  await expect(page.getByText('cancelled · Current revision')).toBeVisible();
  await page.getByRole('button', {name: 'Samples', exact: true}).click();
  await page.getByLabel('Sample label').fill('First fitting');
  await page.locator('select[name=component]').selectOption('sleeve-right');
  await page.getByLabel('Observation').fill('Sleeve needs additional ease');
  await page.getByLabel('Severity').selectOption('blocking');
  await page.getByText('Optional measured evidence').click();
  await page.getByLabel('Measurement name').fill('Sleeve circumference');
  await page.getByLabel('Measured value').fill('32.5');
  await page.getByLabel('Measurement source').fill('Synthetic fitting measurement');
  await page.getByRole('button', {name: 'Record sample finding'}).click();
  await expect(page.getByText('Sleeve needs additional ease')).toBeVisible();
  await page.reload();
  await page.getByRole('button', {name: 'Samples', exact: true}).click();
  await expect(page.getByText('Sleeve circumference: 32.5 cm')).toBeVisible();
  await page.getByLabel('Patternmaker resolution').fill('Allow additional sleeve ease');
  await page.getByRole('button', {name: 'Record resolution'}).click();
  await expect(page.getByText('Resolution: Allow additional sleeve ease')).toBeVisible();
  await page.getByRole('button', {name: 'Components', exact: true}).click();
  await mkdir(artifacts, {recursive: true});
  await page.screenshot({path: resolve(artifacts, 'studio-desktop.png'), fullPage: true});
  expect(errors).toEqual([]);
});

test('mobile studio has no horizontal overflow and cookie proxy rejects cross-origin writes', async ({page}) => {
  await page.setViewportSize({width: 390, height: 844});
  await page.goto('/');
  await page.screenshot({path: resolve(artifacts, 'welcome-mobile.png'), fullPage: true});
  await page.getByRole('link', {name: /Enter your studio/}).click();
  await expect(page.getByRole('heading', {name: 'Burgundy blouse'})).toBeVisible();
  await page.getByRole('button', {name: 'Samples', exact: true}).click();
  await expect(page.getByText('Resolution: Allow additional sleeve ease')).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  const result = await page.request.post('/api/backend/v1/projects', {headers: {Origin: 'https://attacker.invalid',
    'Idempotency-Key': 'csrf-test'}, data: {name: 'Forged'}});
  expect(result.status()).toBe(403);
  await page.screenshot({path: resolve(artifacts, 'studio-mobile.png'), fullPage: true});
  for (const [label,width,height] of [['tablet',768,1024],['wide',1920,1080]] as const) {
    await page.setViewportSize({width,height});
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
    await page.screenshot({path: resolve(artifacts, `studio-${label}.png`), fullPage: true});
  }
  await page.getByRole('button', {name: 'Components', exact: true}).click();
  const pdfHref = await page.getByRole('link', {name: 'Download review PDF'}).first().getAttribute('href');
  expect(pdfHref).toBeTruthy();
  await page.getByRole('button', {name: 'Sign out', exact: true}).click();
  await expect(page.getByRole('heading', {name: /Your vision/})).toBeVisible();
  expect((await page.request.get('/api/backend/v1/projects')).status()).toBe(401);
  expect((await page.request.get(pdfHref!)).status()).toBe(401);
});

